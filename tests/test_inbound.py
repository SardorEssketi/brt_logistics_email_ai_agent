OWN = ["rec1@gmail.com"]


def raw(s: str) -> bytes:
    return s.replace("\n", "\r\n").encode()


GMAIL_BOUNCE = raw("""From: Mail Delivery Subsystem <mailer-daemon@googlemail.com>
To: rec1@gmail.com
Subject: Delivery Status Notification (Failure)
X-Failed-Recipients: gone@example.com
Content-Type: multipart/report; report-type=delivery-status; boundary="B"
MIME-Version: 1.0

--B
Content-Type: text/plain

Address not found. Your message wasn't delivered to gone@example.com
--B
Content-Type: message/delivery-status

Reporting-MTA: dns; googlemail.com

Final-Recipient: rfc822; gone@example.com
Action: failed
Status: 5.1.1

--B
Content-Type: text/rfc822-headers

From: Mike <rec1@gmail.com>
To: gone@example.com
Message-ID: <abc123@test.duckdns.org>
Subject: CDL-A job

--B--
""")

DELAYED = raw("""From: Mail Delivery Subsystem <mailer-daemon@googlemail.com>
Subject: Delivery Status Notification (Delay)
Content-Type: multipart/report; report-type=delivery-status; boundary="B"
MIME-Version: 1.0

--B
Content-Type: text/plain

Still trying.
--B
Content-Type: message/delivery-status

Reporting-MTA: dns; googlemail.com

Final-Recipient: rfc822; slow@example.com
Action: delayed
Status: 4.4.1

--B--
""")


def reply(body, subject="Re: CDL-A dry van, $0.65 CPM", frm="Joe <joe@gmail.com>", refs="<abc123@test.duckdns.org>",
          extra=""):
    return raw(f"""From: {frm}
To: rec1@gmail.com
Subject: {subject}
In-Reply-To: {refs}
References: {refs}
{extra}Content-Type: text/plain; charset=utf-8
MIME-Version: 1.0

{body}
""")


QUOTED = """Yes I'm interested, call me after 5. What lanes?

On Tue, Nov 18, 2026 at 10:02 AM Mike <rec1@gmail.com> wrote:
> Hi Joe,
> We pay $0.65 CPM.
> --
> Not interested? Reply "unsubscribe" or click: https://x/u/1.abc
"""


def kind(r):
    return classify.classify(classify.parse(r), OWN)


def test_bounce():
    k = kind(GMAIL_BOUNCE)
    assert k["kind"] == "bounce" and k["failed"] == ["gone@example.com"]
    assert "<abc123@test.duckdns.org>" in k["refs"]


def test_delay_notice_is_not_bounce():
    assert kind(DELAYED)["kind"] == "ignore"


def test_reply_with_quoted_footer_is_reply_not_unsub():
    assert kind(reply(QUOTED))["kind"] == "reply"


def test_unsubscribe_variants():
    for body in ["Please remove me from your list", "unsubscribe", "STOP", "Not interested, thanks",
                 "stop emailing me", "No thanks"]:
        assert kind(reply(body))["kind"] == "unsubscribe", body
    # Gmail's built-in unsubscribe button: bare mail with subject 'unsubscribe', no references
    assert kind(raw("From: joe@gmail.com\nTo: rec1@gmail.com\nSubject: unsubscribe\n\nThis message was "
                    "automatically generated by Gmail."))["kind"] == "unsubscribe"


def test_truck_stop_is_a_reply():
    assert kind(reply("I'm at a truck stop in Amarillo, can talk tomorrow. Can you remove the forced dispatch?"))[
        "kind"] == "reply"


def test_auto_reply_ignored():
    assert kind(reply("I'm on the road until Monday.", subject="Automatic reply: CDL-A job"))["kind"] == "auto"
    assert kind(reply("Away", extra="Auto-Submitted: auto-replied\n"))["kind"] == "auto"


def test_own_messages_ignored():
    assert kind(reply("hello", frm="rec1@gmail.com"))["kind"] == "ignore"


def _sent_row(conn, email, mid):
    cur = conn.execute("INSERT INTO campaigns(name,created_at,status,source_type,source_ref,mapping,notes_col,header_row) "
                       "VALUES('t',?, 'running','gsheet','mock://x',?,5,1)", (time.time(), json.dumps({"email": 4})))
    cid = cur.lastrowid
    conn.execute("INSERT INTO recipients(campaign_id,row_num,email,status,message_id,sent_at,account_id) "
                 "VALUES(?,?,?,'sent',?,?,1)", (cid, 2, email, mid, time.time()))
    return cid


def test_recording_outcomes(conn):
    add_account(conn, "rec1@gmail.com")
    cid = _sent_row(conn, "gone@example.com", "<abc123@test.duckdns.org>")
    assert process_message(conn, GMAIL_BOUNCE, OWN) == "bounce"
    assert db.suppression_reason(conn, "gone@example.com") == "bounced"
    assert conn.execute("SELECT note FROM marks WHERE campaign_id=?", (cid,)).fetchone()[0].startswith("Bounced ")
    # processing the same message again does not add a second note
    process_message(conn, GMAIL_BOUNCE, OWN)
    assert conn.execute("SELECT COUNT(*) FROM marks").fetchone()[0] == 1

    cid2 = _sent_row(conn, "joe@gmail.com", "<j1@test.duckdns.org>")
    assert process_message(conn, reply(QUOTED, refs="<j1@test.duckdns.org>"), OWN) == "reply"
    assert db.suppression_reason(conn, "joe@gmail.com") == "replied"
    assert process_message(conn, reply("unsubscribe", refs="<j1@test.duckdns.org>"), OWN) == "unsubscribe"
    assert db.suppression_reason(conn, "joe@gmail.com") == "unsubscribed"
    notes = [r[0] for r in conn.execute("SELECT note FROM marks WHERE campaign_id=? ORDER BY id", (cid2,))]
    assert notes[0].startswith("Replied ") and notes[1].startswith("Unsubscribed ")

    # Mail from a stranger is ignored
    assert process_message(conn, reply("hi", frm="stranger@gmail.com", refs="<zzz@x>"), OWN) == "ignore"
    assert db.suppression_reason(conn, "stranger@gmail.com") is None


def test_auto_pause_on_bounce_rate(conn):
    cur = conn.execute("INSERT INTO campaigns(name,created_at,status,source_type,source_ref,mapping,notes_col,header_row) "
                       "VALUES('t',?, 'running','gsheet','mock://x','{}',5,1)", (time.time(),))
    cid = cur.lastrowid
    for i in range(40):
        conn.execute("INSERT INTO recipients(campaign_id,row_num,email,status,sent_at) VALUES(?,?,?,'sent',?)",
                     (cid, i + 2, f"d{i}@x.com", time.time()))
    rows = conn.execute("SELECT * FROM recipients WHERE campaign_id=?", (cid,)).fetchall()
    outcomes.record(conn, "bounced", rows[0])
    assert conn.execute("SELECT status FROM campaigns WHERE id=?", (cid,)).fetchone()[0] == "running"  # 1/40 = 2.5%: below 3%
    outcomes.record(conn, "bounced", rows[1])   # 2/40 = 5% > 3%
    c = conn.execute("SELECT * FROM campaigns WHERE id=?", (cid,)).fetchone()
    assert c["status"] == "paused" and "bounced" in c["status_reason"]
